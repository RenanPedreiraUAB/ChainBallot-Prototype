using ConfigurationComponent.Domain;

namespace ConfigurationComponent.Blockchain;

/// <summary>
/// Defines blockchain operations required to manage election lifecycle state on Solana.
/// </summary>
public interface ISolanaService
{
    /// <summary>
    /// Deploys an election configuration to the blockchain and returns deployment identifiers.
    /// </summary>
    /// <param name="election">Election definition to deploy.</param>
    /// <param name="metadataHash">Canonical hash of the deployed metadata payload.</param>
    /// <param name="metadataUri">Published metadata location.</param>
    /// <param name="cancellationToken">Cancellation token for cooperative cancellation.</param>
    /// <returns>Deployment details generated by the blockchain integration.</returns>
    Task<DeploymentResult> DeployElectionAsync(
        ElectionConfiguration election,
        string metadataHash,
        string metadataUri,
        CancellationToken cancellationToken = default);

    /// <summary>
    /// Initializes an already-deployed election with its metadata fingerprint.
    /// </summary>
    /// <param name="election">Election to initialize.</param>
    /// <param name="metadataHash">Canonical metadata hash.</param>
    /// <param name="cancellationToken">Cancellation token for cooperative cancellation.</param>
    Task InitializeElectionAsync(ElectionConfiguration election, string metadataHash, CancellationToken cancellationToken = default);

    /// <summary>
    /// Activates an election for voting.
    /// </summary>
    /// <param name="electionId">Election identifier.</param>
    /// <param name="cancellationToken">Cancellation token for cooperative cancellation.</param>
    Task ActivateElectionAsync(Guid electionId, CancellationToken cancellationToken = default);

    /// <summary>
    /// Closes an election and transitions it out of active voting.
    /// </summary>
    /// <param name="electionId">Election identifier.</param>
    /// <param name="cancellationToken">Cancellation token for cooperative cancellation.</param>
    Task CloseElectionAsync(Guid electionId, CancellationToken cancellationToken = default);

    /// <summary>
    /// Gets the current blockchain lifecycle status for an election.
    /// </summary>
    /// <param name="electionId">Election identifier.</param>
    /// <param name="cancellationToken">Cancellation token for cooperative cancellation.</param>
    /// <returns>Current lifecycle state known by the blockchain integration.</returns>
    Task<ElectionLifecycleState> GetElectionStatusAsync(Guid electionId, CancellationToken cancellationToken = default);
}
